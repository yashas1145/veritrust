CREATE TABLE credentials (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    credential_id VARCHAR2(100 CHAR) NOT NULL,

    student_id NUMBER NOT NULL,

    institution_id NUMBER NOT NULL,

    credential_type VARCHAR2(100 CHAR) NOT NULL,

    title VARCHAR2(255 CHAR) NOT NULL,

    description VARCHAR2(1000 CHAR),

    issue_date DATE NOT NULL,

    status VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT uk_credentials_credential_id
        UNIQUE (credential_id),

    CONSTRAINT fk_credentials_student
        FOREIGN KEY (student_id)
            REFERENCES users(id),

    CONSTRAINT fk_credentials_institution
        FOREIGN KEY (institution_id)
            REFERENCES institutions(id),

    CONSTRAINT chk_credentials_status
        CHECK (status IN ('ACTIVE', 'REVOKED'))
);