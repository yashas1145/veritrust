CREATE TABLE institutions (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id NUMBER NOT NULL,

    institution_code VARCHAR2(50 CHAR) NOT NULL,

    legal_name VARCHAR2(255 CHAR) NOT NULL,

    address VARCHAR2(500 CHAR),

    country VARCHAR2(100 CHAR),

    verified NUMBER(1) DEFAULT 0 NOT NULL,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT uk_institutions_code
        UNIQUE (institution_code),

    CONSTRAINT uk_institutions_user
        UNIQUE (user_id),

    CONSTRAINT fk_institutions_user
        FOREIGN KEY (user_id)
            REFERENCES users(id),

    CONSTRAINT chk_institutions_verified
        CHECK (verified IN (0, 1))
);